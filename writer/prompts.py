# --- 共通の書き方ルール --------------------------------------------------------

_COMMON_RULES = """
守ること:
- 出力は日本語。前置き・後書き・「承知しました」などの挨拶は書かず、成果物そのものだけを返す。
- 事実が確認できない事柄を断定しない。推測が必要な箇所は、推測だと分かる書き方にする。
- 「〜と言えるでしょう」「いかがでしたか」のような中身のない定型句は使わない。
- 同じ内容の言い換えによる水増しをしない。指定された分量に届かない場合は、無理に伸ばさず中身で埋める。
""".strip()


def _optional(label: str, value: str | None) -> str:
    """入力が空なら行ごと省略する。"""
    value = (value or "").strip()
    return f"{label}: {value}\n" if value else ""


# --- ブログ記事 ---------------------------------------------------------------

# SEO モードで追加されるルール。
# 検索意図を満たすことを最優先し、キーワードの詰め込み（現在は逆効果）はさせない。
_SEO_RULES = """
SEO で守ること（検索から読まれることを前提に書く）:
- 最優先は検索意図を満たすこと。キーワードを不自然に繰り返さない。詰め込みは順位を下げる。
- タイトルは全角 30 文字前後。対策キーワードをなるべく左側に置き、数字か具体語を 1 つ入れる。
- 導入は 120 文字以内。1 文目で読者の疑問に対する答えに触れ、対策キーワードを 1 回だけ自然に含める。
- 見出しは `## ` を主軸にし、階層が必要なときだけ `### ` を使う。
  見出しは体言止めか疑問形にし、関連語・言い換え語を自然に含める。
- 1 つの `## ` セクションは 300〜600 文字。長くなるなら見出しを分ける。
- 各セクションは結論を先に書き、理由や手順を後に置く（検索結果に抜粋されやすくするため）。
- 手順・比較・条件は箇条書きか表にする。表は 3 列以内に収める。
- 具体例・数値・実際の手順を必ず入れる。体験や一次情報に基づく記述を優先する。
- 想定される検索クエリの言い換え（共起語・関連語）を本文に自然に散らす。
""".strip()


def _seo_output_format(include_faq: bool) -> str:
    steps = [
        "1. 先頭に YAML フロントマターを `---` で囲んで置く。含める項目:\n"
        "   title: 記事タイトル（全角 30 文字前後）\n"
        "   description: メタディスクリプション（全角 120 文字前後。"
        "対策キーワードを含め、読むと何が分かるかを書く）\n"
        "   keywords: 対策キーワードと関連語をカンマ区切りで 3〜6 個",
        "2. フロントマターの後に `# 記事タイトル` から本文を始める。",
    ]
    if include_faq:
        steps.append(
            "3. 本文の最後に `## よくある質問` を置き、想定される検索クエリ 3 件に対して "
            "`### 質問文` と 2〜3 文の回答で答える。"
        )
    return "出力の形式:\n" + "\n".join(steps)


def build_blog(
    *,
    theme: str,
    audience: str = "",
    tone: str = "カジュアル",
    target_chars: int = 2000,
    keywords: str = "",
    outline: str = "",
    extra: str = "",
    seo: bool = False,
    seo_keyword: str = "",
    include_faq: bool = True,
) -> tuple[str, str]:
    blocks = [
        "あなたは日本語のブログ記事を書くプロのライター兼編集者です。",
        "読者が読み終えたときに「知らなかったことが分かった」「明日から試せる」と感じる記事を書きます。",
        "",
        "書き方:",
        "- Markdown 形式。記事タイトルは `# `、見出しは `## ` と `### ` を使う。",
        "- 冒頭 2〜3 文で、この記事を読むと何が得られるかを示す。",
        "- 抽象論だけで終わらせず、具体例・数字・手順のいずれかを必ず含める。",
        "- 最後は簡潔なまとめで締める。読者への問いかけで水増ししない。",
        f"- トーン: {BLOG_TONES.get(tone, tone)}",
        "",
        _COMMON_RULES,
    ]

    if seo:
        blocks += ["", _SEO_RULES, "", _seo_output_format(include_faq)]

    system = "\n".join(blocks).strip()

    prompt = (
        "以下の条件でブログ記事を執筆してください。\n\n"
        f"テーマ: {theme.strip()}\n"
        + _optional("想定読者", audience)
        + f"目安の文字数: {target_chars} 文字前後\n"
        + (_optional("対策キーワード（検索されたい語）", seo_keyword) if seo else "")
        + _optional("盛り込みたいキーワード", keywords)
        + _optional("希望する構成・見出し案", outline)
        + _optional("その他の指示", extra)
    )
    return system, prompt


# --- メール文面 ---------------------------------------------------------------

def build_email(
    *,
    purpose: str,
    recipient: str = "",
    points: str = "",
    tone: str = "丁寧（社外向け）",
    length: str = "標準",
    original: str = "",
    extra: str = "",
) -> tuple[str, str]:
    system = f"""
あなたは日本のビジネスメールに精通した文章のプロです。
相手が読んですぐ用件と依頼内容を理解でき、失礼にならないメールを書きます。

書き方:
- 「件名:」から始め、1 行空けて本文を書く。
- 本文は 宛名 → 挨拶 → 用件 → 依頼や次のアクション → 結びの順で構成する。
- 二重敬語や過剰にへりくだった表現は避け、読みやすさを優先する。
- 日時・金額・固有名詞など、こちらが把握していない情報は勝手に作らず
  `【要確認: ○○】` のように埋めるべき箇所として明示する。
- トーン: {EMAIL_TONES.get(tone, tone)}
- 分量: {EMAIL_LENGTHS.get(length, length)}

{_COMMON_RULES}
""".strip()

    prompt = (
        "以下の条件でメールの文面を作成してください。\n\n"
        f"メールの目的: {purpose.strip()}\n"
        + _optional("宛先（相手と自分の関係）", recipient)
        + _optional("必ず伝えたい要点", points)
        + _optional("その他の指示", extra)
        + (
            f"\n--- 返信元のメール本文（ここに返信する） ---\n{original.strip()}\n"
            if original.strip()
            else ""
        )
    )
    return system, prompt


# --- 文章要約 -----------------------------------------------------------------

def build_summary(
    *,
    source_text: str,
    style: str = "3行まとめ",
    target_chars: int = 400,
    purpose: str = "",
    focus: str = "",
) -> tuple[str, str]:
    system = f"""
あなたは正確さを最優先する要約者です。

守ること:
- 原文にない情報・数値・固有名詞を絶対に足さない。原文の主張を勝手に強めたり弱めたりしない。
- 原文で結論が出ていない論点は「結論は出ていない」と書く。
- 要約の形式: {SUMMARY_FORMATS.get(style, style)}
- 全体の分量: {target_chars} 文字前後。
- 出力は要約のみ。「以下が要約です」等の前置きは書かない。

{_COMMON_RULES}
""".strip()

    prompt = (
        "次の文章を要約してください。\n"
        + _optional("要約の用途・想定読者", purpose)
        + _optional("特に重視してほしい観点", focus)
        + f"\n--- 原文ここから ---\n{source_text.strip()}\n--- 原文ここまで ---"
    )
    return system, prompt
